"""macOS installer for the Mica daemon.

Run once with sudo; afterwards launchd starts the daemon at boot as the
``_mica`` system user, with no password needed:

    sudo /usr/bin/python3 -m mica install

What install does (``--dry-run`` prints it without changing anything):

  1. creates a hidden ``_mica`` user and group (no login shell, no home)
  2. copies this package to /usr/local/libexec/mica, owned by root, and
     writes the daemon's config.json there
  3. creates the store (/Library/Mica) owned by _mica, and gives
     your user read-only access to it through an ACL entry
  4. gives _mica read-only access to your transcript folders through
     ACL entries (plus pass-through "search" on the folders above them)
  5. installs /Library/LaunchDaemons/local.mica.plist and starts it

The daemon runs under a root-owned interpreter (Apple's Python 3.9) with -I,
so nothing in your environment (PYTHONPATH, user site-packages, a conda env)
can change the code it runs.
"""

from __future__ import annotations

import grp
import os
import plistlib
import pwd
import re
import shutil
import stat as stat_mod
import subprocess
import sys
import time
from pathlib import Path

from mica import capture
from mica import store as v

SERVICE_USER = "_mica"
ADMIN_GIDS = frozenset({0, 80})  # wheel, admin
LABEL = "local.mica"
LIBEXEC_DIR = Path("/usr/local/libexec/mica")
PLIST_PATH = Path("/Library/LaunchDaemons") / f"{LABEL}.plist"
DEFAULT_PYTHON = "/usr/bin/python3"
PACKAGE_DIR = Path(__file__).resolve().parent
PACKAGE_FILES = ("__init__.py", "__main__.py", "store.py", "capture.py", "install.py")

# One inheritable entry per transcript folder. Directories get list/search;
# files created later inherit it as read (+ execute, since macOS maps
# search->execute on files; harmless for a daemon that only reads).
SOURCE_ACE = f"user:{SERVICE_USER} allow list,search,readattr,readextattr,readsecurity,file_inherit,directory_inherit"
ANCESTOR_ACE = f"user:{SERVICE_USER} allow search"

RUN_PY = '''"""Launcher for the installed mica daemon (generated by install)."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# -I leaves the script's own directory off sys.path; add it explicitly.
sys.path.insert(0, HERE)
from mica.__main__ import main  # noqa: E402

sys.exit(main(["daemon", "--config", os.path.join(HERE, "config.json")]))
'''


def mica_read_ace(user: str) -> str:
    return f"user:{user} allow list,search,readattr,readextattr,readsecurity,file_inherit,directory_inherit"


# ---------------------------------------------------------------------------
# Plan: a list of steps, each a description plus a command or a function
# ---------------------------------------------------------------------------
class Step:
    def __init__(self, text: str, argv=None, func=None, check: bool = True):
        self.text = text
        self.argv = argv
        self.func = func
        self.check = check

    def describe(self) -> str:
        if self.argv:
            return "  $ " + " ".join(_quote(a) for a in self.argv)
        return "  - " + self.text

    def run(self) -> None:
        if self.argv:
            subprocess.run(self.argv, check=self.check, stdout=subprocess.DEVNULL)
        else:
            self.func()


def _quote(arg: str) -> str:
    return arg if re.fullmatch(r"[A-Za-z0-9_./:=@,+-]+", arg) else "'" + arg.replace("'", "'\\''") + "'"


def _run_plan(steps: list, dry_run: bool) -> None:
    for step in steps:
        print(step.describe())
        if not dry_run:
            step.run()


# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------
def _require_macos_root(dry_run: bool) -> None:
    if sys.platform != "darwin":
        raise SystemExit("the Mica installer currently supports macOS only")
    if os.geteuid() != 0 and not dry_run:
        raise SystemExit("run with sudo: sudo /usr/bin/python3 -m mica install")


def _target_user(name: str | None):
    name = name or os.environ.get("SUDO_USER")
    if not name or name == "root":
        raise SystemExit("could not tell whose transcripts to protect; pass --user NAME")
    try:
        return pwd.getpwnam(name)
    except KeyError:
        raise SystemExit(f"no such user: {name}")


def root_owned_chain(path: Path) -> list:
    """Problems that would let a non-root user change ``path``: any component
    from it up to / that is not owned by root or is group/world-writable."""
    problems = []
    current = Path(path)
    while True:
        try:
            st = os.stat(current)
        except OSError as exc:
            problems.append(f"{current}: {exc.strerror}")
            break
        if st.st_uid != 0:
            problems.append(f"{current} is owned by uid {st.st_uid}, not root")
        if st.st_mode & (stat_mod.S_IWGRP | stat_mod.S_IWOTH) and not (st.st_mode & stat_mod.S_ISVTX):
            problems.append(f"{current} is writable by group/others")
        if current.parent == current:
            break
        current = current.parent
    return problems


def resolve_interpreter(python: str) -> tuple:
    """(real executable, sys.prefix) of ``python``, refusing anything a
    non-root user could modify."""
    out = subprocess.run(
        [python, "-I", "-c", "import sys; print(sys.executable); print(sys.prefix); print(sys.version_info[:2] >= (3, 9))"],
        check=True, capture_output=True, text=True,
    ).stdout.split("\n")
    exe, prefix, new_enough = Path(out[0]).resolve(), Path(out[1]).resolve(), out[2] == "True"
    if not new_enough:
        raise SystemExit(f"{python} is older than Python 3.9")
    problems = root_owned_chain(exe) + root_owned_chain(prefix)
    if problems:
        raise SystemExit(
            f"refusing to run the daemon with {exe}: an agent running as you could modify it.\n  "
            + "\n  ".join(problems)
            + "\nUse Apple's /usr/bin/python3 (install the Command Line Tools if it's missing)."
        )
    return str(exe), str(prefix)


def _free_id(start: int = 300, stop: int = 500) -> int:
    used = set()
    for kind, attr in (("/Users", "UniqueID"), ("/Groups", "PrimaryGroupID")):
        out = subprocess.run(["dscl", ".", "-list", kind, attr], capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if parts and parts[-1].lstrip("-").isdigit():
                used.add(int(parts[-1]))
    for candidate in range(start, stop):
        if candidate not in used:
            return candidate
    raise SystemExit("no free system uid/gid between 300 and 500")


def _service_user_exists(target_user=None) -> bool:
    """Reuse only an isolated account matching the one this installer creates.

    A name alone is not an isolation boundary: duplicate numeric IDs or
    extra group members would give other users access to the store.
    All checks are read-only and happen before confirmation or plan execution.
    """
    try:
        account = pwd.getpwnam(SERVICE_USER)
    except KeyError:
        try:
            grp.getgrnam(SERVICE_USER)
        except KeyError:
            return False
        raise SystemExit(f"refusing to overwrite existing group {SERVICE_USER}: its user is missing")

    problems = []
    if not 300 <= account.pw_uid < 500:
        problems.append("uid must be in the installer's system-account range (300–499)")
    if target_user is not None and account.pw_uid == target_user.pw_uid:
        problems.append("shares the transcript owner's uid")
    if account.pw_shell != "/usr/bin/false" or account.pw_dir != "/var/empty":
        problems.append("must have shell /usr/bin/false and home /var/empty")
    try:
        group = grp.getgrnam(SERVICE_USER)
    except KeyError:
        problems.append(f"group {SERVICE_USER} is missing")
    else:
        if group.gr_gid != account.pw_gid or group.gr_gid != account.pw_uid:
            problems.append("user and group must have the same dedicated uid/gid")
        if any(name != SERVICE_USER for name in group.gr_mem):
            problems.append("other users are members of the service group")

    try:
        users = pwd.getpwall()
        if any(p.pw_uid == account.pw_uid and p.pw_name != SERVICE_USER for p in users):
            problems.append("another account shares its uid")
        if any(p.pw_gid == account.pw_gid and p.pw_name != SERVICE_USER for p in users):
            problems.append("another account uses its primary group")
        if any(g.gr_gid == account.pw_gid and g.gr_name != SERVICE_USER for g in grp.getgrall()):
            problems.append("another group shares its gid")
        # macOS reports every local account as a member of everyone,
        # localaccounts, _lpoperator and the sharepoint groups (all nested
        # from everyone/localaccounts), so a fresh account never has only its
        # own group. Reject explicit extra memberships, and administrator
        # groups however they are reached.
        if set(os.getgrouplist(SERVICE_USER, account.pw_gid)) & ADMIN_GIDS:
            problems.append("belongs to an administrator group")
        if any(SERVICE_USER in g.gr_mem and g.gr_name != SERVICE_USER for g in grp.getgrall()):
            problems.append("belongs to groups besides its dedicated service group")
        # Password '*' alone is insufficient if a ShadowHash or other
        # authentication authority has subsequently been configured.
        result = subprocess.run(
            ["/usr/bin/dscl", "-plist", ".", "-read", f"/Users/{SERVICE_USER}"],
            check=True, capture_output=True,
        )
        attrs = plistlib.loads(result.stdout)
        expected = {
            "UniqueID": str(account.pw_uid), "PrimaryGroupID": str(account.pw_gid),
            "UserShell": "/usr/bin/false", "NFSHomeDirectory": "/var/empty", "Password": "*",
        }
        if not isinstance(attrs, dict):
            problems.append("local account metadata is not a dictionary")
        else:
            for key, value in expected.items():
                if attrs.get(f"dsAttrTypeStandard:{key}") != [value]:
                    problems.append(f"local account has unexpected {key}")
            if attrs.get("dsAttrTypeStandard:AuthenticationAuthority"):
                problems.append("has a configured authentication authority")
    except (OSError, subprocess.CalledProcessError, ValueError, plistlib.InvalidFileException):
        problems.append("could not verify account metadata and group memberships")

    if problems:
        raise SystemExit(f"refusing to reuse {SERVICE_USER}:\n  " + "\n  ".join(problems))
    return True


# ---------------------------------------------------------------------------
# ACL helpers
# ---------------------------------------------------------------------------
_ACE_LINE = re.compile(r"^\s*(\d+):\s+(\S+)\s")


def _ace_indices(path: Path, principal: str) -> list:
    """Indices of ACL entries on ``path`` naming ``principal`` (highest first,
    so removing them one by one keeps the remaining indices valid)."""
    out = subprocess.run(["ls", "-led", str(path)], capture_output=True, text=True).stdout
    hits = []
    for line in out.splitlines()[1:]:
        m = _ACE_LINE.match(line)
        if m and m.group(2) == principal:
            hits.append(int(m.group(1)))
    return sorted(hits, reverse=True)


def remove_aces(root: Path, principal: str, recursive: bool) -> None:
    paths = [root]
    if recursive and root.is_dir() and not root.is_symlink():
        for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
            paths.extend(Path(dirpath) / n for n in dirnames + filenames)
    for path in paths:
        if path.is_symlink():
            continue
        for index in _ace_indices(path, principal):
            subprocess.run(["chmod", "-a#", str(index), str(path)], check=False)


def _ancestors(home: Path, root: Path) -> list:
    """Directories from ``home`` down to (not including) ``root``."""
    try:
        rel = root.relative_to(home)
    except ValueError:
        return []
    out, current = [home], home
    for part in rel.parts[:-1]:
        current = current / part
        out.append(current)
    return out


