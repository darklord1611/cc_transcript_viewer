def add_install_args(ap) -> None:
    ap.add_argument("--user", help="whose transcripts to protect (default: the sudo caller)")
    ap.add_argument("--store", default=str(v.DEFAULT_STORE_DIR), help="store directory")
    ap.add_argument("--python", default=DEFAULT_PYTHON, help="root-owned Python 3.9+ for the daemon")
    ap.add_argument("--poll", type=float, default=capture.DEFAULT_POLL_SECONDS, help="seconds between polls")
    ap.add_argument("--yes", action="store_true", help="don't ask for confirmation")
    ap.add_argument("--dry-run", action="store_true", help="print the plan without changing anything")


def build_install_plan(user, store_dir: Path, python_exe: str, poll: float, service_exists: bool, free_id=None) -> tuple:
    """(steps, sources, notes) for installing for ``user`` (a pwd entry)."""
    home = Path(os.path.realpath(user.pw_dir))
    sources = capture.default_sources(home)
    notes = []
    steps = []

    if not service_exists:
        ident = str(free_id() if callable(free_id) else free_id)
        group = f"/Groups/{SERVICE_USER}"
        account = f"/Users/{SERVICE_USER}"
        steps += [
            Step("create group", ["dscl", ".", "-create", group]),
            Step("group id", ["dscl", ".", "-create", group, "PrimaryGroupID", ident]),
            Step("group name", ["dscl", ".", "-create", group, "RealName", "Mica Helper"]),
            Step("group password", ["dscl", ".", "-create", group, "Password", "*"]),
            Step("create user", ["dscl", ".", "-create", account]),
            Step("user id", ["dscl", ".", "-create", account, "UniqueID", ident]),
            Step("user group", ["dscl", ".", "-create", account, "PrimaryGroupID", ident]),
            Step("no login shell", ["dscl", ".", "-create", account, "UserShell", "/usr/bin/false"]),
            Step("no home", ["dscl", ".", "-create", account, "NFSHomeDirectory", "/var/empty"]),
            Step("user name", ["dscl", ".", "-create", account, "RealName", "Mica Helper"]),
            Step("no password", ["dscl", ".", "-create", account, "Password", "*"]),
            Step("hidden", ["dscl", ".", "-create", account, "IsHidden", "1"]),
        ]

    kept_sources = []
    for src in sources:
        if src.root.is_dir():
            kept_sources.append(src)
        elif src.root.parent.is_dir():
            # e.g. ~/.codex/archived_sessions before Codex first archives a
            # session: create it now so it carries the ACL from the start.
            kept_sources.append(src)
            steps.append(Step(f"create {src.root}", func=_mkdir_as(src.root, user)))
        else:
            notes.append(f"skipping {src.name}: {src.root.parent} does not exist (re-run install after installing it)")

    config = {
        "mica": str(store_dir),
        "poll_seconds": poll,
        "user": user.pw_name,
        "sources": [s.to_json() for s in kept_sources],
    }
    steps.append(Step(f"install daemon code to {LIBEXEC_DIR} (root-owned)", func=lambda: _install_code(config)))

    steps += [
        Step("create mica", ["mkdir", "-p", str(store_dir)]),
        Step("mica owner", ["chown", f"{SERVICE_USER}:{SERVICE_USER}", str(store_dir)]),
        Step("mica mode", ["chmod", "750", str(store_dir)]),
        Step(f"clear old mica ACL entries for {user.pw_name}",
             func=lambda: remove_aces(store_dir, f"user:{user.pw_name}", recursive=True)),
        Step(f"let {user.pw_name} read the store", ["chmod", "-R", "+a", mica_read_ace(user.pw_name), str(store_dir)]),
    ]

    ancestors = []
    for src in kept_sources:
        for d in _ancestors(home, src.root):
            if d not in ancestors:
                ancestors.append(d)
    for d in ancestors:
        steps.append(Step(f"clear old entries on {d}", func=lambda d=d: remove_aces(d, f"user:{SERVICE_USER}", False)))
        steps.append(Step(f"pass-through on {d}", ["chmod", "+a", ANCESTOR_ACE, str(d)]))
    for src in kept_sources:
        steps.append(Step(f"clear old entries under {src.root}",
                          func=lambda r=src.root: remove_aces(r, f"user:{SERVICE_USER}", True)))
        steps.append(Step(f"read access to {src.root}", ["chmod", "-R", "+a", SOURCE_ACE, str(src.root)]))

    steps += [
        Step(f"write {PLIST_PATH}", func=lambda: _write_plist(python_exe, store_dir)),
        Step("stop any running copy", ["launchctl", "bootout", f"system/{LABEL}"], check=False),
        Step("start at boot", ["launchctl", "enable", f"system/{LABEL}"]),
        Step("start now", ["launchctl", "bootstrap", "system", str(PLIST_PATH)]),
    ]
    return steps, kept_sources, notes


def _mkdir_as(path: Path, user):
    def run():
        path.mkdir(exist_ok=True)
        os.chown(path, user.pw_uid, user.pw_gid)
        os.chmod(path, 0o755)
    return run


def _install_code(config: dict) -> None:
    import json

    if LIBEXEC_DIR.exists():
        shutil.rmtree(LIBEXEC_DIR)
    pkg = LIBEXEC_DIR / "mica"
    pkg.mkdir(parents=True)
    for name in PACKAGE_FILES:
        shutil.copyfile(PACKAGE_DIR / name, pkg / name)
    (LIBEXEC_DIR / "run.py").write_text(RUN_PY, encoding="utf-8")
    (LIBEXEC_DIR / "config.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    for dirpath, dirnames, filenames in os.walk(LIBEXEC_DIR):
        os.chown(dirpath, 0, 0)
        os.chmod(dirpath, 0o755)
        for name in filenames:
            os.chown(os.path.join(dirpath, name), 0, 0)
            os.chmod(os.path.join(dirpath, name), 0o644)
    # /usr/local is user-owned on some Macs (old Homebrew installs); if any
    # parent is, an agent could swap the daemon's code, so refuse.
    problems = root_owned_chain(LIBEXEC_DIR / "run.py")
    if problems:
        shutil.rmtree(LIBEXEC_DIR, ignore_errors=True)
        raise SystemExit("installed code would not be protected:\n  " + "\n  ".join(problems))


def plist_dict(python_exe: str, store_dir: Path) -> dict:
    return {
        "Label": LABEL,
        "ProgramArguments": [python_exe, "-I", "-B", str(LIBEXEC_DIR / "run.py")],
        "UserName": SERVICE_USER,
        "GroupName": SERVICE_USER,
        "RunAtLoad": True,
        "KeepAlive": True,
        "ProcessType": "Background",
        "LowPriorityIO": True,
        "Nice": 10,
        "Umask": 0o027,
        "WorkingDirectory": str(LIBEXEC_DIR),
        "EnvironmentVariables": {"HOME": "/var/empty"},
        "StandardOutPath": str(store_dir / "daemon.log"),
        "StandardErrorPath": str(store_dir / "daemon.log"),
    }


def _write_plist(python_exe: str, store_dir: Path) -> None:
    with open(PLIST_PATH, "wb") as fh:
        plistlib.dump(plist_dict(python_exe, store_dir), fh)
    os.chown(PLIST_PATH, 0, 0)
    os.chmod(PLIST_PATH, 0o644)


def _confirm(prompt: str) -> bool:
    try:
        return input(prompt + " [y/N] ").strip().lower() in ("y", "yes")
    except EOFError:
        return False


def cmd_install(args) -> int:
    _require_macos_root(args.dry_run)
    user = _target_user(args.user)
    service_exists = _service_user_exists(user)
    store_dir = Path(args.store)
    existing = store_dir.parent
    while not existing.exists():
        existing = existing.parent
    problems = root_owned_chain(existing)
    if problems:
        raise SystemExit(
            f"refusing mica location {store_dir}: a folder above it is not root-owned, so an agent "
            "could move the store aside.\n  " + "\n  ".join(problems)
        )
    python_exe, _prefix = resolve_interpreter(args.python)
    steps, sources, notes = build_install_plan(
        user, store_dir, python_exe, args.poll, service_exists, free_id=_free_id,
    )
    print(f"Mica install for {user.pw_name}")
    print(f"  daemon user:   {SERVICE_USER}")
    print(f"  interpreter:   {python_exe}")
    print(f"  store:         {store_dir}")
    for src in sources:
        print(f"  capture:       {src.root}")
    for note in notes:
        print(f"  note: {note}")
    print()
    if args.dry_run:
        print("Plan (dry run, nothing changed):")
        _run_plan(steps, dry_run=True)
        return 0
    if not args.yes and not _confirm("Proceed?"):
        print("aborted")
        return 1
    _run_plan(steps, dry_run=False)
    print("\nwaiting for the first heartbeat…")
    reader = v.StoreReader(store_dir)
    for _ in range(40):
        if reader.available() and reader.status()["running"]:
            status = reader.status()
            print(f"running: {status['n_files']} transcripts captured so far.")
            print(f"Point the viewer at it (it finds {v.DEFAULT_STORE_DIR} automatically).")
            return 0
        time.sleep(0.5)
    print(f"no heartbeat yet; check {store_dir / 'daemon.log'} and `launchctl print system/{LABEL}`")
    return 1


# ---------------------------------------------------------------------------
# Uninstall
# ---------------------------------------------------------------------------
def add_uninstall_args(ap) -> None:
    ap.add_argument("--user", help="whose transcript folders carry the ACL entries (default: the sudo caller)")
    ap.add_argument("--store", default=str(v.DEFAULT_STORE_DIR))
    ap.add_argument("--delete-store", action="store_true",
                    help="also delete every captured transcript (default: keep them, owned by root)")
    ap.add_argument("--yes", action="store_true")
    ap.add_argument("--dry-run", action="store_true")


def build_uninstall_plan(user, store_dir: Path, delete_store: bool) -> list:
    home = Path(os.path.realpath(user.pw_dir))
    sources = capture.default_sources(home)
    steps = [
        Step("stop the daemon", ["launchctl", "bootout", f"system/{LABEL}"], check=False),
        Step(f"remove {PLIST_PATH}", ["rm", "-f", str(PLIST_PATH)]),
        Step(f"remove {LIBEXEC_DIR}", ["rm", "-rf", str(LIBEXEC_DIR)]),
    ]
    ancestors = []
    for src in sources:
        steps.append(Step(f"remove {SERVICE_USER} ACL entries under {src.root}",
                          func=lambda r=src.root: remove_aces(r, f"user:{SERVICE_USER}", True)))
        for d in _ancestors(home, src.root):
            if d not in ancestors:
                ancestors.append(d)
    for d in ancestors:
        steps.append(Step(f"remove pass-through on {d}", func=lambda d=d: remove_aces(d, f"user:{SERVICE_USER}", False)))
    if delete_store:
        steps.append(Step(f"delete {store_dir}", ["rm", "-rf", str(store_dir)]))
    else:
        steps.append(Step(f"keep {store_dir}, owned by root", ["chown", "-R", "root:wheel", str(store_dir)], check=False))
    steps += [
        Step("delete user", ["dscl", ".", "-delete", f"/Users/{SERVICE_USER}"], check=False),
        Step("delete group", ["dscl", ".", "-delete", f"/Groups/{SERVICE_USER}"], check=False),
    ]
    return steps


def cmd_uninstall(args) -> int:
    _require_macos_root(args.dry_run)
    user = _target_user(args.user)
    steps = build_uninstall_plan(user, Path(args.store), args.delete_store)
    if args.dry_run:
        print("Plan (dry run, nothing changed):")
        _run_plan(steps, dry_run=True)
        return 0
    what = "and DELETE all captured transcripts" if args.delete_store else "(captured transcripts are kept)"
    if not args.yes and not _confirm(f"Uninstall Mica {what}?"):
        print("aborted")
        return 1
    _run_plan(steps, dry_run=False)
    print("uninstalled")
    return 0
